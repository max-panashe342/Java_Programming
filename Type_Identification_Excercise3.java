/*
Exercise 3: Type identification

Declare these variables using the correct data types:
- A person's age: 22
- Temperature: 36.5
- First letter of your name: P
- Country: Zimbabwe
- Is Java interesting?: true
Print each variable.
 */

public class Type_Identification_Excercise3 {
    public static void main(String[] args){
        int age = 22;
        double temperature = 36.5;
        char first_letter = 'P';
        String country = "Zimbabwe";
        boolean isJavaInteresting = true;
        System.out.println(age);
        System.out.println(temperature);
        System.out.println(first_letter);
        System.out.println(country);
        System.out.println(isJavaInteresting);
    }


}
