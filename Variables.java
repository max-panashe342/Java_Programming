//VARIABLES

//variable is a named memory location used to store data that a program can use and manipulate.
//Think of a variable as a container. You give the container a name and put some information inside it.
//age,length,height,name,grade are variables because they store values.e.g age stores 23.
public class Variables {
    public static void main(String[] args){
        int age = 23;
        double length = 1.66;
        float height = 0.4f;
        String name = "Panashe";
        char grade = 'A';
        boolean isStudent = true;

        System.out.println(age);
        System.out.println(length);
        System.out.println(height);
        System.out.println(name);
        System.out.println(grade);
        System.out.println(isStudent);
    }

}
